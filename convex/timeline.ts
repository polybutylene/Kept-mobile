// ═════════════════════════════════════════════════════════════
// User-created timeline events (manual entries)
// ═════════════════════════════════════════════════════════════

export const addManualEvent = mutation({
  args: {
    homeId: v.id("homes"),
    systemId: v.optional(v.id("systems")),
    eventType: v.string(),
    title: v.string(),
    description: v.optional(v.string()),
    cost: v.optional(v.number()),
    costType: v.optional(v.string()),
    performedBy: v.optional(v.string()),
    date: v.optional(v.number()),
  },
  handler: async (ctx, args) => {
    const identity = await ctx.auth.getUserIdentity();
    if (!identity) throw new Error("Not authenticated");

    const user = await ctx.db
      .query("users")
      .withIndex("email", (q) => q.eq("email", identity.email!))
      .first();
    if (!user) throw new Error("User not found");

    const iconMap: Record<string, string> = {
      service_call: "🔧",
      task_completed: "✅",
      system_added: "➕",
      system_replaced: "🔄",
      document_uploaded: "📄",
      receipt_uploaded: "🧾",
      cost_recorded: "💰",
      note: "📝",
    };

    const colorMap: Record<string, string> = {
      service_call: "amber",
      task_completed: "green",
      system_added: "teal",
      system_replaced: "blue",
      document_uploaded: "gray",
      receipt_uploaded: "gray",
      cost_recorded: "emerald",
      note: "gray",
    };

    return await ctx.db.insert("timelineEvents", {
      userId: user._id,
      homeId: args.homeId,
      systemId: args.systemId,
      eventType: args.eventType,
      title: args.title,
      description: args.description,
      icon: iconMap[args.eventType] ?? "📝",
      color: colorMap[args.eventType] ?? "gray",
      cost: args.cost,
      costType: args.costType,
      performedBy: args.performedBy,
      isUserGenerated: true,
      isAutoGenerated: false,
      timestamp: args.date ?? Date.now(),
    });
  },
});
