export const getTimeline = query({
  args: {
    homeId: v.id("homes"),
    limit: v.optional(v.number()),
    eventType: v.optional(v.string()),
  },
  handler: async (ctx, args) => {
    const limit = args.limit ?? 50;

    if (args.eventType) {
      const events = await ctx.db
        .query("timelineEvents")
        .withIndex("by_homeId", (q) => q.eq("homeId", args.homeId))
        .order("desc")
        .take(limit * 3);

      return events
        .filter((e) => e.eventType === args.eventType)
        .slice(0, limit);
    }

    return await ctx.db
      .query("timelineEvents")
      .withIndex("by_homeId_timestamp", (q) => q.eq("homeId", args.homeId))
      .order("desc")
      .take(limit);
  },
});

export const getTimelineByMonth = query({
  args: {
    homeId: v.id("homes"),
    year: v.number(),
    month: v.number(),
  },
  handler: async (ctx, args) => {
    const startOfMonth = new Date(args.year, args.month - 1, 1).getTime();
    const endOfMonth = new Date(args.year, args.month, 0, 23, 59, 59).getTime();

    const events = await ctx.db
      .query("timelineEvents")
      .withIndex("by_homeId_timestamp", (q) =>
        q.eq("homeId", args.homeId).gte("timestamp", startOfMonth).lte("timestamp", endOfMonth)
      )
      .order("desc")
      .take(200);

    return events;
  },
});

export const getTimelineStats = query({
  args: {
    homeId: v.id("homes"),
    year: v.optional(v.number()),
  },
  handler: async (ctx, args) => {
    const year = args.year ?? new Date().getFullYear();
    const startOfYear = new Date(year, 0, 1).getTime();
    const endOfYear = new Date(year, 11, 31, 23, 59, 59).getTime();

    const events = await ctx.db
      .query("timelineEvents")
      .withIndex("by_homeId_timestamp", (q) =>
        q.eq("homeId", args.homeId).gte("timestamp", startOfYear).lte("timestamp", endOfYear)
      )
      .take(500);

    const tasksCompleted = events.filter(
      (e) => e.eventType === "task_completed",
    ).length;
    const totalSpent = events
      .filter((e) => e.cost && e.cost > 0)
      .reduce((sum, e) => sum + (e.cost ?? 0), 0);
    const diySavings = events
      .filter((e) => e.costType === "diy_savings")
      .reduce((sum, e) => sum + (e.cost ?? 0), 0);

    const byType: Record<string, number> = {};
    for (const e of events) {
      byType[e.eventType] = (byType[e.eventType] ?? 0) + 1;
    }

    return {
      year,
      totalEvents: events.length,
      tasksCompleted,
      totalSpent: Math.round(totalSpent),
      diySavings: Math.round(diySavings),
      byType,
    };
  },
});

